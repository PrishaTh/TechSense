/**
 * Embeds the supplied rental application PDF into the Worker unchanged.
 *
 * Usage: put the file at private/RENTAL_APPLICATION_FORM.pdf, then run
 *   npm run embed:application
 * The Worker serves these exact bytes and reports this exact SHA-256.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "private", "RENTAL_APPLICATION_FORM.pdf");
const target = join(root, "worker", "applicationFile.ts");

const pdf = await readFile(source);
const checksum = createHash("sha256").update(pdf).digest("hex");
const base64 = pdf.toString("base64");

const contents = `/**
 * The supplied rental application PDF, served byte for byte.
 *
 * Generated by \`npm run embed:application\` from
 * \`private/RENTAL_APPLICATION_FORM.pdf\`. Do not edit by hand.
 */
export const APPLICATION_FILE_NAME = "RENTAL_APPLICATION_FORM.pdf";
export const APPLICATION_FILE_PATH = "private/RENTAL_APPLICATION_FORM.pdf";
export const APPLICATION_SHA256 = "${checksum}";
export const APPLICATION_BASE64 =
  "${base64}";

let cached: Uint8Array | null = null;

export function applicationPdfBytes(): Uint8Array | null {
  if (!APPLICATION_BASE64) return null;
  if (cached) return cached;
  const binary = atob(APPLICATION_BASE64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) {
    bytes[i] = binary.charCodeAt(i);
  }
  cached = bytes;
  return bytes;
}
`;

await writeFile(target, contents, "utf8");
console.log(`Embedded ${pdf.byteLength} bytes · SHA-256 ${checksum}`);
